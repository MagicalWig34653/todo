#!/bin/sh
# Embeds docs/agent-manual.md into Sources/TodoKit/MCP/AgentManualContent.swift (ADR 0014).
# Run after every change to the manual; the test AgentManualTests.testEmbeddedManualIsCurrent fails on a stale copy.
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
src="$root/docs/agent-manual.md"
out="$root/Sources/TodoKit/MCP/AgentManualContent.swift"
if grep -q '"""' "$src" || grep -q '\\#' "$src"; then echo "manual must not contain triple quotes or \\#" >&2; exit 1; fi
{
  printf '// Generated by scripts/embed-agent-manual.sh from docs/agent-manual.md. Do not edit.\n'
  printf 'enum AgentManualContent {\n    static let text = #"""\n'
  cat "$src"
  printf '"""#\n}\n'
} > "$out"
echo "wrote $out"
